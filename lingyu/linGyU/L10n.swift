/// Localisation. Every user-visible string goes through `L()` with the
/// Chinese literal as the key; the English table maps the same literal.
/// Fallback is always the Chinese literal itself, so a missing translation
/// never shows a key. The table is verified by the pre-push check (§5.1).
func L(_ zh: String, _ args: CVarArg...) -> String {
    let format = L10n.string(for: zh)
    guard !args.isEmpty else { return format }
    return String(format: format, arguments: args)
}

