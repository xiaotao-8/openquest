    ## 10. 体量与范围
    交付完整可用的内容，不管多长。不许为了短而阉割可用的文件。
    简洁是针对闲话的，不是针对代码的。任务需要 900 行，900 行就是正确长度。
    宁要少而密的文件，不要多而稀的文件。
    不许交付任何东西的"缩减版"。
    """
